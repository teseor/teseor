import { describe, expect, test } from "vitest";
import type { Spec } from "../../gen-contract.ts";
import { renderCompositeListVueWrapper } from "./composite-list.ts";

function paginationFixture(): Spec {
  return {
    name: "pagination",
    kind: "composite",
    props: {},
    tokens: {},
    states: {},
    parts: {
      root: { element: "nav", rootClass: "t-pagination" },
      page: {
        repeating: true,
        element: "a",
        rootClass: "t-pagination-page",
        props: {
          label: { type: "string", slot: true, description: "Page label." },
          current: { type: "boolean", description: "Active page." },
          href: { type: "string", description: "Target URL (data-attr in phase 1)." },
        },
      },
    },
    repeating: [
      {
        partName: "page",
        propName: "pages",
        element: "a",
        rootClass: "t-pagination-page",
        itemProps: {
          label: { type: "string", slot: true, description: "Page label." },
          current: { type: "boolean", description: "Active page." },
          href: { type: "string", description: "Target URL (data-attr in phase 1)." },
        },
      },
    ],
  };
}

describe("renderCompositeListVueWrapper (RFC-0005)", () => {
  test('opens with the AUTOGENERATED comment + `script setup lang="ts"`', () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out.startsWith("<!-- AUTOGENERATED by gen-vue. Do not edit. -->")).toBe(true);
    expect(out).toContain(`<script setup lang="ts">`);
    expect(out).toContain("<!-- Source: specs/pagination.yaml -->");
  });

  test("imports the per-component CSS", () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out).toContain(`import "@teseor/css/components/pagination.css";`);
  });

  test("exports an Item type per repeating part with required `id: string`", () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out).toContain("export type PaginationPageItem = {");
    expect(out).toContain("  id: string;");
  });

  test('emits the `export type` in a sibling `<script lang="ts">` block, not inside `<script setup>`', () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    const exportIdx = out.indexOf("export type PaginationPageItem");
    const setupIdx = out.indexOf(`<script setup lang="ts">`);
    expect(exportIdx).toBeGreaterThan(-1);
    expect(setupIdx).toBeGreaterThan(-1);
    expect(exportIdx).toBeLessThan(setupIdx);
    // The plain `<script lang="ts">` block opens before the exports.
    const plainScriptIdx = out.indexOf(`<script lang="ts">`);
    expect(plainScriptIdx).toBeLessThan(exportIdx);
    expect(plainScriptIdx).toBeLessThan(setupIdx);
  });

  test("declares the array prop type", () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out).toContain("pages?: ReadonlyArray<PaginationPageItem>;");
  });

  test("destructures the array prop with a [] default", () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out).toContain("pages = [],");
  });

  test("renders the wrapper element from the non-repeating part", () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out).toContain(`<nav class="t-pagination">`);
    expect(out).toContain("</nav>");
  });

  test('emits a v-for over the array prop with :key="item.id"', () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out).toContain(`v-for="item in pages"`);
    expect(out).toContain(`:key="item.id"`);
  });

  test("slot-marked prop renders as `{{ item.x }}` interpolation", () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out).toContain("{{ item.label }}");
  });

  test("non-slot string prop renders as `:data-x` binding", () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out).toContain(`:data-href="item.href"`);
  });

  test("boolean prop renders with `|| undefined` fallback", () => {
    const out = renderCompositeListVueWrapper(paginationFixture());
    expect(out).toContain(`:data-current="item.current || undefined"`);
  });
});
