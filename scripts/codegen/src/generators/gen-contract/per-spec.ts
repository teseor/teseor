import type { FlatSpec } from "../../lib/flatten.ts";
import { pascalCase } from "../../lib/pascal-case.ts";
import { itemTypeName } from "../../lib/repeating-naming.ts";
import { renderPayloadFields } from "./_shared/payload-printer.ts";
import { collectStatefulParts, stateTypeName } from "./_shared/states.ts";
import { mapPropType, quote, responsiveType } from "./_shared/type-printer.ts";

/** Per-spec contract emitter. `FlatSpec` already collapses the atomic vs
 *  composite distinction (composite parts are merged into root props with a
 *  `__part` marker), so a single render path covers both kinds. */
export function renderContract(spec: FlatSpec): string {
  const Name = pascalCase(spec.name);
  const lines: string[] = [];

  lines.push(`// AUTOGENERATED by gen-contract. Do not edit.`);
  lines.push(`// Source: specs/${spec.name}.yaml`);
  lines.push("");

  const hasResponsive = Object.values(spec.props).some(
    (d) => d.responsive === true && d.slot !== true,
  );
  if (hasResponsive) {
    lines.push(`import type { Responsive } from "./_responsive.ts";`);
    lines.push("");
  }

  if (spec.variants && Object.keys(spec.variants).length > 0) {
    const values = Object.keys(spec.variants).map(quote).join(" | ");
    lines.push(`export type ${Name}Variant = ${values};`);
    lines.push("");
  }
  if (spec.intents && Object.keys(spec.intents).length > 0) {
    const values = Object.keys(spec.intents).map(quote).join(" | ");
    lines.push(`export type ${Name}Intent = ${values};`);
    lines.push("");
  }
  if (spec.sizes && Object.keys(spec.sizes).length > 0) {
    const values = Object.keys(spec.sizes).map(quote).join(" | ");
    lines.push(`export type ${Name}Size = ${values};`);
    lines.push("");
  }

  for (const [propName, propDef] of Object.entries(spec.props)) {
    const values = propDef.values ?? [];
    if (values.length > 0) {
      lines.push(`export type ${Name}${pascalCase(propName)} = ${values.map(quote).join(" | ")};`);
      lines.push("");
    }
  }

  const propLines: string[] = [];
  if (spec.variants) propLines.push(`  variant?: ${Name}Variant;`);
  if (spec.intents) propLines.push(`  intent?: ${Name}Intent;`);
  if (spec.sizes) propLines.push(`  size?: ${Name}Size;`);

  // Atomic specs declare `constraints` at the root; surface them in the
  // contract's JSDoc so consumers see the runtime invariants. Composite specs
  // don't carry constraints at the root.
  if (spec.constraints && spec.constraints.length > 0) {
    lines.push("/**");
    lines.push(" * Runtime constraints (enforced in dev builds):");
    for (const c of spec.constraints) {
      const when = JSON.stringify(c.when ?? {});
      const forbid = JSON.stringify(c.forbid ?? {});
      lines.push(` *   when ${when} forbid ${forbid}`);
      if (c.reason) lines.push(` *     ${c.reason}`);
    }
    lines.push(" */");
  }

  for (const [propName, propDef] of Object.entries(spec.props)) {
    if (propDef.pattern === "controllable" && propDef.type === "boolean") {
      // Expand the controllable triple — `name` + `defaultName` + `onNameChange`.
      const PName = pascalCase(propName);
      if (propDef.description) propLines.push(`  /** ${propDef.description} */`);
      propLines.push(`  ${propName}?: boolean;`);
      propLines.push(`  /** Initial open state (uncontrolled). */`);
      propLines.push(`  default${PName}?: boolean;`);
      propLines.push(`  /** Fires when the open state changes. */`);
      propLines.push(`  on${PName}Change?: (${propName}: boolean) => void;`);
      continue;
    }
    const propValues = propDef.values ?? [];
    // Slot kinds in the contract:
    //  - Atomic-root slot (e.g. Button's `iconStart`): renderable child.
    //    Contract emits `unknown`; React widens to ReactNode, Vue maps to
    //    a named slot via `defineSlots`.
    //  - Composite-part slot (e.g. Tooltip's `text` on the `content` part):
    //    scalar body content (string in the contract). React + Vue wrappers
    //    use the same scalar type.
    // The `__part` marker (set by flattenSpec) distinguishes the two: empty
    // string for atomic-root props, the originating part name for composite.
    // `__part` is "" for atomic-root props (set by flattenSpec) and the
    // originating part name for composite. Tests that bypass flatten see
    // `undefined`; treat both empty and missing as the atomic-root case.
    const isAtomicSlot = propDef.slot === true && !propDef.__part;
    const baseType = isAtomicSlot
      ? "unknown"
      : propValues.length > 0
        ? `${Name}${pascalCase(propName)}`
        : mapPropType(propDef.type);
    const tsType =
      propDef.responsive === true && propDef.slot !== true ? responsiveType(baseType) : baseType;
    if (propDef.description) propLines.push(`  /** ${propDef.description} */`);
    propLines.push(`  ${propName}?: ${tsType};`);
  }

  // Repeating parts: parts sharing the same `groupKey:` merge into ONE Item
  // type + ONE array prop. Ungrouped repeating parts each get their own.
  // Group by effective propName (flatten already collapses sibling parts to
  // the same propName when they share a groupKey).
  const repeatingGroups = new Map<string, typeof spec.repeating>();
  for (const r of spec.repeating ?? []) {
    const group = repeatingGroups.get(r.propName) ?? [];
    group.push(r);
    repeatingGroups.set(r.propName, group);
  }

  const itemTypeLines: string[] = [];
  for (const [propName, group] of repeatingGroups) {
    if (!group || group.length === 0) continue;
    const first = group[0];
    if (!first) continue;
    const ItemName = itemTypeName(Name, first);
    const mergedItemProps: Array<[string, (typeof group)[number]["itemProps"][string]]> = [];
    const seen = new Set<string>();
    for (const part of group) {
      for (const [n, def] of Object.entries(part.itemProps)) {
        if (seen.has(n)) continue;
        seen.add(n);
        mergedItemProps.push([n, def]);
      }
    }
    itemTypeLines.push(`export type ${ItemName} = {`);
    itemTypeLines.push(`  /** Stable item identity; required. */`);
    itemTypeLines.push(`  id: string;`);
    for (const [itemPropName, propDef] of mergedItemProps) {
      const propValues = propDef.values ?? [];
      const baseType =
        propValues.length > 0 ? propValues.map(quote).join(" | ") : mapPropType(propDef.type);
      if (propDef.description) itemTypeLines.push(`  /** ${propDef.description} */`);
      itemTypeLines.push(`  ${itemPropName}?: ${baseType};`);
    }
    itemTypeLines.push("};");
    itemTypeLines.push("");
    const docPartName =
      group.length === 1
        ? `\`${first.partName}\``
        : group.map((g) => `\`${g.partName}\``).join(" + ");
    propLines.push(
      `  /** Items rendered by the repeating ${docPartName} part${group.length > 1 ? "s" : ""}. */`,
    );
    propLines.push(`  ${propName}?: ReadonlyArray<${ItemName}>;`);
  }
  for (const line of itemTypeLines) lines.push(line);

  // Generics parameter list — `<Item>`, `<Item, Row>`, … — attached to both
  // `<Spec>Props` and `<Spec>Event` so consumers can pass the type at the
  // call site (`<Combobox<User> …/>`).
  const genericNames = (spec.generics ?? []).map((g) => g.name);
  const genericParams = genericNames.length > 0 ? `<${genericNames.join(", ")}>` : "";

  // Per-event surface — only emitted when `events:` is declared. Controllable
  // mirrors contribute arms to the channel union even though their per-event
  // prop is still the existing `on<Prop>Change` callback.
  const events = spec.events ?? {};
  const declaredEventNames = Object.keys(events);
  const hasEvents = declaredEventNames.length > 0;

  if (hasEvents) {
    const controllableBooleanProps = Object.entries(spec.props)
      .filter(([_n, def]) => def.pattern === "controllable" && def.type === "boolean")
      .map(([n]) => n);

    const unionArms: string[] = [];
    for (const eventName of declaredEventNames) {
      const entry = events[eventName];
      if (!entry) continue;
      const fields = renderPayloadFields(entry.payload);
      const arm = fields ? `{ type: "${eventName}"; ${fields} }` : `{ type: "${eventName}" }`;
      unionArms.push(`  | ${arm}`);
    }
    for (const propName of controllableBooleanProps) {
      unionArms.push(`  | { type: "${propName}Change"; value: boolean }`);
    }

    lines.push(`export type ${Name}Event${genericParams} =`);
    lines.push(`${unionArms.join("\n")};`);
    lines.push("");

    // Per-event handler props sit just after the configured props. Empty-payload
    // events use the parameterless form so consumers writing `onClear={fn}` don't
    // have to accept an unused argument.
    for (const eventName of declaredEventNames) {
      const entry = events[eventName];
      if (!entry) continue;
      const fields = renderPayloadFields(entry.payload);
      const sig = fields ? `(e: { ${fields} }) => void` : `() => void`;
      const handlerName = `on${pascalCase(eventName)}`;
      if (entry.description) propLines.push(`  /** ${entry.description} */`);
      propLines.push(`  ${handlerName}?: ${sig};`);
    }

    propLines.push(`  /** Aggregated event channel: fires for every declared event and every`);
    propLines.push(`   *  controllable state mirror. Per-emission ordering: declared event prop →`);
    propLines.push(`   *  channel → controllable callback → channel. */`);
    propLines.push(`  onEvent?: (e: ${Name}Event${genericParams}) => void;`);
  }

  // Per-part state unions. Generated from each part's `states:` map so
  // consumers can name the union at `useState`-style boundaries without
  // re-deriving it. Single-part case collapses to `<Spec>State`.
  const statefulParts = collectStatefulParts(spec.parts);
  for (const { partName, stateNames } of statefulParts) {
    const typeName = stateTypeName(Name, partName, statefulParts.length);
    const values = stateNames.map(quote).join(" | ");
    lines.push(`export type ${typeName} = ${values};`);
    lines.push("");
  }

  if (propLines.length === 0) {
    lines.push(`export type ${Name}Props${genericParams} = Record<string, never>;`);
  } else {
    lines.push(`export type ${Name}Props${genericParams} = {`);
    for (const line of propLines) lines.push(line);
    lines.push("};");
  }
  lines.push("");

  return lines.join("\n");
}
