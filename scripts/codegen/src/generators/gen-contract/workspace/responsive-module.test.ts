import { describe, expect, test } from "vitest";
import type { Breakpoint } from "../../../lib/breakpoints.ts";
import { renderResponsiveModule } from "./responsive-module.ts";

const FIXTURE: Breakpoint[] = [
  { name: "sm", minWidth: "480px" },
  { name: "md", minWidth: "768px" },
];

describe("renderResponsiveModule", () => {
  test("emits a Breakpoint union prefixed with `base`", () => {
    const out = renderResponsiveModule(FIXTURE);
    expect(out).toContain('type Breakpoint = "base" | "sm" | "md";');
  });

  test("emits the Responsive<T> alias", () => {
    const out = renderResponsiveModule(FIXTURE);
    expect(out).toContain("export type Responsive<T> = T | Partial<Record<Breakpoint, T>>;");
  });

  test("starts with the AUTOGENERATED banner", () => {
    const out = renderResponsiveModule(FIXTURE);
    expect(out.split("\n")[0]).toBe("// AUTOGENERATED by gen-contract. Do not edit.");
  });

  test("renders identically on repeated calls", () => {
    expect(renderResponsiveModule(FIXTURE)).toBe(renderResponsiveModule(FIXTURE));
  });
});
