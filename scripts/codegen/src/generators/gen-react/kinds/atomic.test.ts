import { describe, expect, test } from "vitest";
import type { Spec, SpecProp } from "../../gen-contract.ts";
import { renderAtomicReactWrapper } from "./atomic.ts";

function prop(overrides: Partial<SpecProp> & { type: SpecProp["type"] }): SpecProp {
  return { description: "", __part: "", ...overrides };
}

function atomicSpec(overrides: Partial<Spec> = {}): Spec {
  return {
    name: "button",
    kind: "atomic",
    props: {},
    tokens: {},
    states: {},
    ...overrides,
  };
}

describe("renderAtomicReactWrapper", () => {
  test("opens with the `use client` directive and the AUTOGENERATED banner", () => {
    const out = renderAtomicReactWrapper(atomicSpec(), {});
    expect(out.startsWith(`"use client";\n`)).toBe(true);
    expect(out).toContain("// AUTOGENERATED by gen-react. Do not edit.");
    expect(out).toContain("// Source: specs/button.yaml");
  });

  test("imports the per-component CSS module", () => {
    const out = renderAtomicReactWrapper(atomicSpec(), {});
    expect(out).toContain(`import "@teseor/css/components/button.css";`);
  });

  test("uses the spec's `element` for the root tag when no `as` prop exists", () => {
    const out = renderAtomicReactWrapper(atomicSpec({ element: "span" }), {});
    expect(out).toContain(`<span\n`);
    expect(out).toContain("</span>");
  });

  test("switches to a polymorphic `Component` when an `as` prop is declared", () => {
    const out = renderAtomicReactWrapper(
      atomicSpec({ props: { as: prop({ type: "string", default: "button" }) } }),
      {},
    );
    expect(out).toContain("const Component = asElement(");
    expect(out).toContain("<Component\n");
    expect(out).toContain("</Component>");
  });

  test("imports the responsive runtime helpers only when there's a responsive prop", () => {
    const noResp = renderAtomicReactWrapper(atomicSpec(), {});
    expect(noResp).not.toContain("responsiveDataAttrs");

    const withResp = renderAtomicReactWrapper(
      atomicSpec({ sizes: { md: { description: "" } } }),
      {},
    );
    expect(withResp).toContain(
      `import { type Responsive, responsiveDataAttrs } from "./_runtime.ts";`,
    );
  });
});
